1. [Priority recommendation]
2. [Next priority recommendation]

---

*Report generated by ClickFlash Audit Kit*
EOF

# Replace TIMESTAMP with actual timestamp
sed -i "s/TIMESTAMP/$DATE $TIMESTAMP/g" "$OUTPUT_DIR/audit_report_$TIMESTAMP.md"

echo "Report generated: $OUTPUT_DIR/audit_report_$TIMESTAMP.md"
echo "Done!"